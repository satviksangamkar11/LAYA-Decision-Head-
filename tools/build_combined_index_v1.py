def sha_file(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def sha_obj(o):
    return hashlib.sha256(json.dumps(o, sort_keys=True, ensure_ascii=True, separators=(",", ":")).encode()).hexdigest()


def rel(p):
    return str(Path(p).resolve().relative_to(ROOT)).replace("\\", "/")


def gz(p):
    return [json.loads(x) for x in gzip.open(p, "rt", encoding="utf-8")]


out_dir = RAW / ("combined-index-v1-" + time.strftime("%Y%m%dT%H%M%SZ", time.gmtime()))
out_dir.mkdir(parents=True, exist_ok=False)  # create-only
rows, sources = [], {}


def src(p):
    sources[rel(p)] = {"sha256": sha_file(p), "bytes": Path(p).stat().st_size}
    return rel(p)


